  // NOTE: the AI Studio export declared `release` and `debugConfig` signing configs
  // pointing at keystores that are not in the zip (my-upload-key.jks / debug.keystore).
  // Declaring them made every build fail with "Keystore file not found".
  // Signing is now handled by the standard Gradle properties below, so debug builds
  // use AGP's auto-generated debug key and release builds read a keystore from
  // gradle.properties / -P flags when you are ready to publish.
  signingConfigs {
    create("release") {
      val ksPath = (project.findProperty("RELEASE_KEYSTORE_PATH") as String?)
      if (ksPath != null && file(ksPath).exists()) {
        storeFile = file(ksPath)
        storePassword = project.findProperty("RELEASE_STORE_PASSWORD") as String?
        keyAlias = project.findProperty("RELEASE_KEY_ALIAS") as String? ?: "upload"
        keyPassword = project.findProperty("RELEASE_KEY_PASSWORD") as String?
      }
    }
  }

  buildTypes {
    release {
      isCrunchPngs = false
      isMinifyEnabled = false
      proguardFiles(getDefaultProguardFile("proguard-android-optimize.txt"), "proguard-rules.pro")
      // Only applied when a real keystore is supplied via -PRELEASE_KEYSTORE_PATH=...
      if ((project.findProperty("RELEASE_KEYSTORE_PATH") as String?) != null) {
        signingConfig = signingConfigs.getByName("release")
      }
    }
    debug { }
  }
  compileOptions {
    sourceCompatibility = JavaVersion.VERSION_11
